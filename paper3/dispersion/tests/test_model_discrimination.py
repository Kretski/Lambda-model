# TEST 2
# =====================================================================

def test_pure_quartic_is_not_lambda_model():
    """
    Pure k^4 dispersion must NOT be interpreted as a Lambda-model
    measurement merely because both contain quartic structure.
    """

    c = 1.0
    beta = 0.02

    k = np.linspace(
        0.15,
        1.2,
        80,
    )

    omega = quartic_dispersion(
        k,
        c,
        beta,
    )

    # Attempt to fit Lambda-model through least squares.
    #
    # For the Lambda model:
    #
    # omega^2 = c^2 k^2 + 2 Lambda c^2 k^4
    #
    # Therefore calculate the best linear coefficient in omega^2.
    #

    y = omega**2 - c**2 * k**2
    x = 2.0 * c**2 * k**4

    lambda_fit = np.dot(x, y) / np.dot(x, x)

    omega_lambda = lambda_dispersion(
        k,
        c,
        lambda_fit,
    )

    residual_lambda = np.sum(
        (omega - omega_lambda)**2
    )

    residual_quartic = np.sum(
        (omega - quartic_dispersion(k, c, beta))**2
    )

    print()
    print("=" * 70)
    print("TEST 2 — PURE QUARTIC NEGATIVE CONTROL")
    print("=" * 70)
    print(f"Injected beta          = {beta:.8e}")
    print(f"Lambda fit attempt     = {lambda_fit:.8e}")
    print(f"Lambda-model RSS       = {residual_lambda:.8e}")
    print(f"Quartic-model RSS      = {residual_quartic:.8e}")

    assert np.isfinite(lambda_fit)

    # The actual quartic model must explain the data substantially
    # better than the Lambda dispersion model.
    assert residual_quartic < residual_lambda


