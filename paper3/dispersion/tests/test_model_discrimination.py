def test_lambda_zero_control():
    """
    Standard linear dispersion (Lambda = 0) must not produce a
    significant positive Lambda estimate.
    """

    c = 1.0

    k = np.linspace(
        0.15,
        1.2,
        80,
    )

    omega = c * k

    lambda_fit = estimate_lambda_direct(
        k,
        omega,
        c,
    )

    print()
    print("=" * 70)
    print("TEST 3 — LAMBDA = 0 CONTROL")
    print("=" * 70)
    print(f"Recovered Lambda = {lambda_fit:.8e}")

    assert abs(lambda_fit) < 1e-10


