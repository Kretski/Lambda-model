"""
Paper 3 — Model Discrimination Regression Test

Purpose
-------
This test verifies that the Lambda fitting machinery:

1. recovers Lambda from synthetic data generated by the Lambda model;
2. rejects a pure quartic k^4 dispersion as evidence for the Lambda model;
3. keeps the photonic/fiber negative-control interpretation separate
   from an actual Lambda measurement.

This is a methodological validation test.
It is NOT an experimental validation of Lambda.
"""

