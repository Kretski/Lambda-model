# TEST 4
# =====================================================================

def test_quartic_scaling():
    """
    Verify that the negative-control dataset has approximately
    fourth-order scaling in its nonlinear component.
    """

    c = 1.0
    beta = 0.02

    k = np.linspace(
        0.2,
        1.2,
        50,
    )

    omega = quartic_dispersion(
        k,
        c,
        beta,
    )

    nonlinear = omega - c * k

    mask = nonlinear > 0

    log_k = np.log(k[mask])
    log_nonlinear = np.log(nonlinear[mask])

    slope, intercept = np.polyfit(
        log_k,
        log_nonlinear,
        1,
    )

    print()
    print("=" * 70)
    print("TEST 4 — QUARTIC STRUCTURAL SCALING")
    print("=" * 70)
    print(f"Expected exponent = 4")
    print(f"Measured exponent = {slope:.8f}")

    assert abs(slope - 4.0) < 1e-10


