# ---------------------------------------------------------------------
# Lambda-model synthetic dispersion
#
# omega = c*k*sqrt(1 + 2*Lambda*k^2)
# ---------------------------------------------------------------------

def lambda_dispersion(k, c, lam):
    return c * k * np.sqrt(1.0 + 2.0 * lam * k**2)


# ---------------------------------------------------------------------
# Pure quartic dispersion
#
# omega = c*k + B*k^4
#
# This deliberately represents a structural quartic control.
# ---------------------------------------------------------------------

def quartic_dispersion(k, c, beta):
    return c * k + beta * k**4


# ---------------------------------------------------------------------
# Simple direct Lambda estimator
#
# From:
#
# omega^2 = c^2 k^2 + 2 Lambda c^2 k^4
#
# Lambda = (omega^2 - c^2 k^2)
#          / (2 c^2 k^4)
# ---------------------------------------------------------------------

def estimate_lambda_direct(k, omega, c):
    numerator = omega**2 - (c * k)**2
    denominator = 2.0 * c**2 * k**4

    values = numerator / denominator

    return np.median(values)


# =====================================================================
# TEST 1
# =====================================================================

def test_lambda_model_recovery():
    """
    Synthetic data generated from the Lambda model must recover
    the injected Lambda value within a reasonable tolerance.
    """

    rng = np.random.default_rng(12345)

    c = 1.0
    lambda_true = 0.05

    k = np.linspace(0.15, 1.2, 80)

    omega_clean = lambda_dispersion(
        k,
        c,
        lambda_true,
    )

    # Small experimental-like noise
    noise = rng.normal(
        0.0,
        2.0e-4,
        size=k.shape,
    )

    omega = omega_clean + noise

    lambda_fit = estimate_lambda_direct(
        k,
        omega,
        c,
    )

    relative_error = abs(
        lambda_fit - lambda_true
    ) / lambda_true

    print()
    print("=" * 70)
    print("TEST 1 — LAMBDA MODEL RECOVERY")
    print("=" * 70)
    print(f"True Lambda       = {lambda_true:.8f}")
    print(f"Recovered Lambda  = {lambda_fit:.8f}")
    print(f"Relative error    = {relative_error:.6e}")

    assert np.isfinite(lambda_fit)

    # Noise makes exact recovery impossible.
    # Require recovery within 5%.
    assert relative_error < 0.05


